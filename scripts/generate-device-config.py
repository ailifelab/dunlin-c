#!/usr/bin/env python3
"""Build-time generation only: no JSON/filesystem parser added to the board."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
LIMITS={'vm_heap_bytes':(65536,1048576),'script_ms':(100,2000),'job_ms':(1000,30000),'code_bytes':(64,2047),'stdout_bytes':(128,1535),'stdout_lines':(1,32),'https_timeout_ms':(100,8000),'max_allowed_hosts':(1,8),'ntp_wait_ms':(0,10000)}
def hostname(value):
    return isinstance(value,str) and 3<=len(value)<96 and '.' in value and all(c.isascii() and (c.islower() or c.isdigit() or c in '.-') for c in value)
def validate(config):
    if config.get('micropython_version')!='1.26.1':raise ValueError('dependency version mismatch')
    for key,(low,high) in LIMITS.items():
        if type(config.get(key)) is not int or not low<=config[key]<=high:raise ValueError('invalid '+key)
    if config.get('network_policy') not in ('trusted_https','allowlist'):raise ValueError('invalid network_policy')
    hosts=config.get('default_allowed_hosts')
    if not isinstance(hosts,list) or not 0<len(hosts)<=config['max_allowed_hosts'] or any(not hostname(h) for h in hosts) or len(set(hosts))!=len(hosts):raise ValueError('invalid default HTTPS hosts')
    if not hostname(config.get('ntp_server')):raise ValueError('invalid NTP host')
    return config
def render(config):
    validate(config)
    result='/* Generated by scripts/generate-device-config.py; edit python.json. */\n'
    for key in LIMITS:result+='#define AP_'+key.upper()+' '+str(config[key])+'u\n'
    result+='#define AP_RESTRICT_HOSTS '+str(int(config['network_policy']=='allowlist'))+'u\n'
    result+='#define AP_NTP_SERVER '+json.dumps(config['ntp_server'])+'\n'
    result+='#define AP_DEFAULT_HOSTS {'+','.join(json.dumps(h) for h in config['default_allowed_hosts'])+'}\n#define AP_DEFAULT_HOST_COUNT '+str(len(config['default_allowed_hosts']))+'u\n'
    return result
def write_changed(path,text):
    if not path.exists() or path.read_text()!=text:path.write_text(text)
def main():
    import argparse
    parser=argparse.ArgumentParser();parser.add_argument('--prompt-only',action='store_true');args=parser.parse_args()
    if not args.prompt_only:
        api=json.loads((ROOT/'dunlin-copilot/esp32/esp32/config/openai.json').read_text())
        for key,low,high in [('max_output_tokens',128,8192),('response_bytes',8192,65536)]:
            if type(api.get(key)) is not int or not low<=api[key]<=high:raise ValueError('invalid OpenAI '+key)
        write_changed(ROOT/'dunlin-copilot/esp32/esp32/config/openai_defaults.h','/* Generated; edit openai.json. */\n'+''.join('#define AE_OPENAI_'+k.upper()+' '+str(api[k])+'u\n' for k in ['max_output_tokens','response_bytes']))
        config=json.loads((ROOT/'dunlin-copilot/esp32/esp32/config/python.json').read_text())
        write_changed(ROOT/'dunlin-copilot/esp32/esp32/config/python_defaults.h',render(config))
        prompt=(ROOT/'dunlin-copilot/esp32/python/system.txt').read_text().strip()
        write_changed(ROOT/'dunlin-copilot/esp32/python/system_prompt.h','/* Generated; edit system.txt. */\nstatic const char python_system_prompt[]='+json.dumps(prompt,ensure_ascii=True)+';\n')
    prompt=(ROOT/'dunlin-copilot/esp32/agent/system.txt').read_text().strip()
    write_changed(ROOT/'dunlin-copilot/esp32/agent/system_prompt.h','/* Generated; edit system.txt. */\nstatic const char device_system_prompt[]='+json.dumps(prompt,ensure_ascii=True)+';\n')
if __name__=='__main__':main()
